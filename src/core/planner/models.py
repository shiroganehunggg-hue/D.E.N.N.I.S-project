from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional


class ErrorDecision(str, Enum):
    """Recovery decision returned by ErrorAnalyzer for a failed step."""
    RETRY = "retry"
    SKIP = "skip"
    REPLAN = "replan"
    ABORT = "abort"


@dataclass
class ErrorAnalysis:
    """Result of analyzing one failed tool execution."""
    decision: ErrorDecision
    reason: str = ""
    user_message: str = ""


@dataclass
class PlanStep:
    """A single executable step inside a plan."""
    tool: str
    args: Dict[str, Any] = field(default_factory=dict)
    timeout: Optional[float] = None
    retries: int = 0
    critical: bool = False


@dataclass
class Plan:
    """A structured execution plan generated by the planner."""
    goal: str
    steps: List[PlanStep] = field(default_factory=list)


@dataclass
class ToolResult:
    """Result of one tool execution."""
    tool: str
    success: bool
    result: str = ""
    data: Any = None
    error: Optional[str] = None
    duration_ms: Optional[float] = None
    duration_seconds: Optional[float] = None

    def __post_init__(self) -> None:
        if self.duration_ms is None and self.duration_seconds is not None:
            self.duration_ms = self.duration_seconds * 1000
        if not self.result and self.data is not None:
            if isinstance(self.data, str):
                self.result = self.data
            else:
                self.result = str(self.data)


@dataclass
class ExecutionResult:
    """Aggregate execution outcome for a plan."""
    goal: str
    completed: bool
    tool_results: List[ToolResult] = field(default_factory=list)
    failure_reason: Optional[str] = None
    error_decision: Optional[ErrorDecision] = None
    failed_step: Optional[PlanStep] = None


@dataclass
class ReflectionResult:
    """Final reflection outcome for the plan."""
    status: str
    summary: str
